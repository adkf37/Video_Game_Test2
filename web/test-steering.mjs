import assert from 'node:assert/strict';
import {TiltSteering, screenRoll} from './mobile/steering.js';
assert.equal(screenRoll(null, 0, 90), null);
assert.equal(screenRoll(NaN, 0, 90), null);
assert(Math.abs(screenRoll(0, 0, 90)) < 1e-6);
assert(screenRoll(-20, 0, 90) > 19.9, 'right turn in first landscape orientation');
assert(screenRoll(20, 0, 270) > 19.9, 'right turn in reversed landscape orientation');
assert(screenRoll(20, 0, 90) < -19.9, 'left turn');
const tilt = new TiltSteering();
tilt.sample(-10, -60, 90);
assert.equal(tilt.update(.1), 0, 'calibrate to the actual holding angle');
tilt.sample(-11, -60, 90);
assert.equal(tilt.update(.1), 0, 'small tremors stay inside the dead zone');
tilt.sample(-35, -60, 90);
assert(tilt.update(.016) > 0 && tilt.value < .3, 'smoothing prevents instant full lock');
for(let i=0;i<100;i++) tilt.update(.016);
assert(tilt.value > .99 && tilt.value <= 1, 'sustained tilt reaches full steering');
tilt.center();
assert.equal(tilt.update(.1), 0, 'recenter cancels existing turn');
tilt.sample(20, 0, 270);
assert.equal(tilt.update(.1), 0, 'orientation change recalibrates without a steering jump');
console.log('STEERING PASS: both landscape directions, neutral calibration, invalid data, dead zone, smoothing, recenter.');
